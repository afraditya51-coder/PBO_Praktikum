public class Increment {
    public static void main(String[] args) {
        int x = 5;

        System.out.println("Nilai awal x = " + x);

        System.out.println("\nx++ = " + (x++));
        System.out.println("Setelah x++, x = " + x);

        System.out.println("\n++x = " + (++x));
        System.out.println("Setelah ++x, x = " + x);
    }
}
